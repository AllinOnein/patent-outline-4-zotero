/**
 * Rasterise the SVG icon sources into the PNG sizes Zotero expects, and embed
 * the ones used from UI code as data URLs (see the note below).
 *
 * Usage: npm i --no-save sharp && node tools/render-icons.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const iconsDir = join(projectRoot, "addon", "content", "icons");
const sourceDir = join(projectRoot, "tools", "icon-src");

const targets = [
  // App icon: manifest (48/96), preferences pane and progress window.
  // Rendered large and downscaled so curves stay smooth.
  {
    source: "app-icon.svg",
    file: "patentoutline.png",
    size: 96,
    density: 384,
    constant: "ICON_APP",
  },
  {
    source: "app-icon.svg",
    file: "patentoutline@0.5x.png",
    size: 48,
    density: 384,
  },
  // Context-menu icons: Zotero renders them at 16px, so they are rasterised
  // 1:1 — scaling a high-density render down blurs the 1px strokes.
  {
    source: "menu-icon.svg",
    file: "patentoutline-16.png",
    size: 16,
    density: 96,
    constant: "ICON_MENU_LIGHT",
  },
  {
    source: "menu-icon-dark.svg",
    file: "patentoutline-16-dark.png",
    size: 16,
    density: 96,
    constant: "ICON_MENU_DARK",
  },
];

const embedded = {};

for (const { source, file, size, density, constant } of targets) {
  const svg = await readFile(join(sourceDir, source));
  const buffer = await sharp(svg, { density })
    .resize(size, size, { kernel: size <= 16 ? "nearest" : "lanczos3" })
    .png({ compressionLevel: 9 })
    .toBuffer();

  await writeFile(join(iconsDir, file), buffer);
  if (constant) {
    embedded[constant] = `data:image/png;base64,${buffer.toString("base64")}`;
  }
  console.log(`${file}: ${size}x${size} @${density}`);
}

// Icons used from UI code are embedded as data URLs: a chrome:// URL into the
// packed XPI does not resolve on every Zotero build, which leaves the menu item
// without an icon, and a data URL removes that dependency completely.
const modulePath = join(projectRoot, "src", "utils", "icons.ts");
const lines = [
  "// Generated by tools/render-icons.mjs — do not edit by hand.",
  "// Run `node tools/render-icons.mjs` after changing tools/icon-src/*.svg.",
  "",
];
for (const [name, value] of Object.entries(embedded)) {
  lines.push(`export const ${name} =`, `  "${value}";`, "");
}
await writeFile(modulePath, lines.join("\n"));
console.log(`src/utils/icons.ts: ${Object.keys(embedded).length} icons`);
